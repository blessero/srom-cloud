/* =====================================================================
   Interface language — English and Polish.

   Short strings are their own English key: t("Save") looks up the Polish
   and falls back to the English. Long texts have a key of their own
   (t("note.venues")) with the English in EN below, so a paragraph lives
   once per language rather than once in the code and again as a key.
   Placeholders are {name}. Plurals go through tn()/tw(): Polish has three
   forms — 1 praca · 2 prace · 5 prac.

   Polish phrasing avoids nouns for a person where it can ("Romologia to
   główny obszar pracy" rather than "Specjalista…"), so a line reads right
   whoever it describes. Names of works, journals and institutions are
   never translated: they are data, shown as the sources record them.
   ===================================================================== */

const I18N = { lang: "en" };

I18N.lang = (() => {
  try { const s = localStorage.getItem("srom.lang"); if (s === "pl" || s === "en") return s; } catch (e) {}
  return /^pl\b/i.test(navigator.language || "") ? "pl" : "en";
})();

const LOCALE = () => I18N.lang === "pl" ? "pl-PL" : "en-GB";

function t(key, vars){
  let s = (I18N.lang === "pl" ? PL[key] : undefined) ?? EN[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

/** Polish: one / few (2–4, not 12–14) / many. */
function plForm(n){
  n = Math.abs(Math.trunc(n));
  if (n === 1) return 0;
  const d = n % 10, h = n % 100;
  return d >= 2 && d <= 4 && !(h >= 12 && h <= 14) ? 1 : 2;
}
/** The word for n of something, without the number. */
function tw(n, key){
  const f = PLURAL[key];
  if (!f) return key;
  return I18N.lang === "pl" ? f.pl[plForm(n)] : f.en[n === 1 ? 0 : 1];
}
/** n and the word for it: "1 work", "5 prac". */
const tn = (n, key) => num(n) + " " + tw(n, key);

